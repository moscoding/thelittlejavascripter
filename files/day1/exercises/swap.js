let a = 'дама червей';
let b = 'туз червей';
// ваш код (через временную переменную)

let x = 7;
let y = 42;
// бонус: ваш код (одной строкой, через деструктуризацию)

// ─── Проверка (не меняйте код ниже) ───
let passed = 0;
let total = 0;

function check(name, actual, expected) {
  total++;
  const got = JSON.stringify(actual);
  const want = JSON.stringify(expected);
  if (got === want) {
    passed++;
    console.log('✓ ' + name);
  } else {
    console.log('✗ ' + name + ' — получено ' + got + ', ожидалось ' + want);
  }
}

check('в a теперь туз', a, 'туз червей');
check('в b теперь дама', b, 'дама червей');
check('бонус: x', x, 42);
check('бонус: y', y, 7);

console.log(passed === total
  ? 'Готово! Все проверки пройдены.'
  : 'Пройдено ' + passed + ' из ' + total);
